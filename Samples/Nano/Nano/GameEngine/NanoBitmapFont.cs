    public static string[]? Rows(char character)
    {
        var normalized = character switch
        {
            'á' or 'à' or 'ä' or 'â' or 'Á' or 'À' or 'Ä' or 'Â' => 'A',
            'é' or 'è' or 'ë' or 'ê' or 'É' or 'È' or 'Ë' or 'Ê' => 'E',
            'í' or 'ì' or 'ï' or 'î' or 'Í' or 'Ì' or 'Ï' or 'Î' => 'I',
            'ó' or 'ò' or 'ö' or 'ô' or 'Ó' or 'Ò' or 'Ö' or 'Ô' => 'O',
            'ú' or 'ù' or 'ü' or 'û' or 'Ú' or 'Ù' or 'Ü' or 'Û' => 'U',
            'ñ' or 'Ñ' => 'N',
            _ => char.ToUpperInvariant(character)
        };
        return s_glyphs.GetValueOrDefault(normalized);
    }

    public static float MeasureWidth(string text, int scale) =>
        Math.Max(0, text.Length * Advance - 1) * Math.Max(1, scale);

    public static float MeasureHeight(int scale) => GlyphHeight * Math.Max(1, scale);
